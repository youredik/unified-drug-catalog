/**
 * Транслитерация кириллицы в латиницу по ГОСТ 7.79-2000, система Б.
 *
 * Зачем: домен российский, а торговые наименования приходят на обеих
 * раскладках — «Нурофен» и «Acmeflex» это один бренд. Без приведения к общему
 * скрипту такие пары не встретятся даже в блокировке кандидатов.
 *
 * Это же снимает известную слабость языковых моделей: по данным OpenSanctions
 * Pairs (arXiv 2603.11051) модели чаще всего ошибаются именно на кросс-скриптовой
 * транслитерации. Поэтому нормализация идёт ДО арбитража, а не после.
 *
 * Система Б передаёт ъ, ь, ы, э модификаторами (`` ` ``, `y'`, `e'`). Для ключа
 * сравнения модификаторы затем схлопываются — `fold` ниже; сам ГОСТ-вывод
 * остаётся доступен отдельно.
 */

const GOST_B: ReadonlyMap<string, string> = new Map([
  ['а', 'a'], ['б', 'b'], ['в', 'v'], ['г', 'g'], ['д', 'd'], ['е', 'e'], ['ё', 'yo'],
  ['ж', 'zh'], ['з', 'z'], ['и', 'i'], ['й', 'j'], ['к', 'k'], ['л', 'l'], ['м', 'm'],
  ['н', 'n'], ['о', 'o'], ['п', 'p'], ['р', 'r'], ['с', 's'], ['т', 't'], ['у', 'u'],
  ['ф', 'f'], ['х', 'x'], ['ц', 'cz'], ['ч', 'ch'], ['ш', 'sh'], ['щ', 'shh'],
  ['ъ', '``'], ['ы', "y'"], ['ь', '`'], ['э', "e'"], ['ю', 'yu'], ['я', 'ya'],
  // украинские и белорусские буквы, встречающиеся в наименованиях
  ['і', 'i'], ['ї', 'yi'], ['є', 'ye'], ['ґ', 'g'], ['ў', 'u'],
]);

/** По системе Б `ц` перед i, e, y, j передаётся как `c`, иначе как `cz`. */
const CZ_SOFT_NEXT = new Set(['и', 'е', 'ы', 'й', 'і', 'ї', 'є']);

export const hasCyrillic = (s: string): boolean => /[Ѐ-ӿ]/.test(s);

/** Транслитерация по ГОСТ 7.79-2000, система Б. */
export const translitGostB = (input: string): string => {
  const chars = [...input];
  let out = '';
  for (let i = 0; i < chars.length; i++) {
    const ch = chars[i]!;
    const lower = ch.toLowerCase();
    const mapped = GOST_B.get(lower);
    if (mapped === undefined) {
      out += ch;
      continue;
    }
    let piece = mapped;
    if (lower === 'ц') {
      const next = chars[i + 1]?.toLowerCase();
      piece = next !== undefined && CZ_SOFT_NEXT.has(next) ? 'c' : 'cz';
    }
    // Сохраняем регистр первой буквы исходного символа
    out += ch !== lower ? piece.charAt(0).toUpperCase() + piece.slice(1) : piece;
  }
  return out;
};

/**
 * Ключ сравнения: транслитерация, затем схлопывание модификаторов ГОСТ,
 * нижний регистр и удаление всего, что не буква и не цифра.
 *
 * `Нурофен` и `Acmeflex` дают один ключ — это и есть цель.
 */
export const foldForCompare = (input: string): string =>
  translitGostB(input)
    .toLowerCase()
    .replace(/[`']/g, '')
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '');
